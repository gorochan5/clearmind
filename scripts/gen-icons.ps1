# Regenera src/icons.rs a partir de resources/lucide/lucide.css.
# Uso (na raiz do projeto): pwsh scripts/gen-icons.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$css = Join-Path $root 'resources/lucide/lucide.css'
$out = Join-Path $root 'src/icons.rs'

$keywords = @('as','break','const','continue','else','enum','extern','false','fn','for','if','impl','in','let','loop','match','mod','move','mut','pub','ref','return','static','struct','trait','true','type','unsafe','use','where','while','async','await','dyn','abstract','become','box','do','final','macro','override','priv','typeof','unsized','virtual','yield','try','gen')
$noRaw = @('self','super','crate')

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('//! Lucide icons rendered from the embedded `lucide.ttf`.')
[void]$sb.AppendLine('//!')
[void]$sb.AppendLine('//! GENERATED by `scripts/gen-icons.ps1` from `resources/lucide/lucide.css`. Do not edit by hand.')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('#![allow(dead_code)]')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('use iced::Font;')
[void]$sb.AppendLine('use iced::widget::Text;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/// Raw bytes of the Lucide font, embedded in the binary.')
[void]$sb.AppendLine('pub const FONT_BYTES: &[u8] = include_bytes!("../resources/lucide/lucide.ttf");')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/// Font family declared inside `lucide.ttf`.')
[void]$sb.AppendLine('pub const FONT: Font = Font::new("lucide");')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('fn icon<''a>(codepoint: char) -> Text<''a> {')
[void]$sb.AppendLine('    iced::widget::text(codepoint).font(FONT)')
[void]$sb.AppendLine('}')

$seen = @{}
$count = 0
foreach ($m in [regex]::Matches((Get-Content $css -Raw), '\.icon-([a-z0-9-]+)::before\s*\{\s*content:\s*"\\([0-9a-fA-F]+)"')) {
    $name = $m.Groups[1].Value.Replace('-', '_')
    if ($name -match '^[0-9]') { $name = "_$name" }
    if ($noRaw -contains $name) { $name = "${name}_" }
    elseif ($keywords -contains $name) { $name = "r#$name" }
    if ($seen.ContainsKey($name)) { continue }
    $seen[$name] = $true
    $count++
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("pub fn $name<'a>() -> Text<'a> {")
    [void]$sb.AppendLine("    icon('\u{$($m.Groups[2].Value.ToLower())}')")
    [void]$sb.AppendLine('}')
}

[System.IO.File]::WriteAllText($out, $sb.ToString(), [System.Text.UTF8Encoding]::new($false))
Write-Host "Generated $count icons -> $out"
